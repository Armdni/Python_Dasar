# Iterasi list
messages = ["morning", "afternoon", "evening"]

for m in messages:
    print(m)

# Iterasi tuple
numbers = ("twenty four", 24)

for n in numbers:
    print(n)

# Iterasi string
for char in "hello python":
    print(char)

# Iterasi dictionary
bio = {
    "name": "toyota camry",
    "year": 1993
}

for key in bio:
    print("key:", key, "value:", bio[key])

# Iterasi set
numbers = {"twenty four", 24}

for n in numbers:
    print(n)