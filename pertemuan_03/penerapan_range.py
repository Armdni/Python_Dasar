# Range sederhana
for i in range(3):
    print("index:", i)

# Range dengan start dan stop
for i in range(0, 3):
    print("index:", i)

# Range dengan start, stop, dan step
for i in range(0, 3, 1):
    print("index:", i)

# Perulangan angka genap
for i in range(2, 10, 2):
    print("index:", i)

# Perulangan menurun
for i in range(5, -5, -1):
    print("index:", i)